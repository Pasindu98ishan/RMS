#!/usr/bin/env node
// Generates src/api/generated/operations.ts from the bundled OpenAPI spec (ADR-005).
// openapi-typescript emits types only and drops vendor extensions, so the runtime facts the client
// and mocks need (x-permission, x-idempotent, x-approval, security: []) are extracted here.
// Usage: node scripts/gen-api-meta.mjs <bundled.yaml> <out.ts>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'
import { parse } from 'yaml'

const [, , input, output] = process.argv
if (!input || !output) {
  console.error('usage: gen-api-meta.mjs <bundled.yaml> <out.ts>')
  process.exit(2)
}

const spec = parse(readFileSync(input, 'utf8'))
const METHODS = ['get', 'put', 'post', 'delete', 'patch']
const globalSecurity = spec.security ?? []
const ops = []

for (const [path, item] of Object.entries(spec.paths ?? {})) {
  for (const method of METHODS) {
    const op = item[method]
    if (!op) continue
    const security = op.security ?? globalSecurity
    ops.push({
      operationId: op.operationId,
      method: method.toUpperCase(),
      path,
      permission: op['x-permission'] ?? 'AUTHENTICATED',
      idempotent: op['x-idempotent'] === true,
      approval: op['x-approval'] ?? null,
      noBearer: Array.isArray(security) && security.length === 0,
      inlineCredentials: op['x-auth'] === 'INLINE_CREDENTIALS',
      terminalRequired: op['x-terminal'] === 'REQUIRED',
    })
  }
}

ops.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))

const body = `// GENERATED by scripts/gen-api-meta.mjs from ${input.replace(/\\/g, '/')} - do not edit.
/* eslint-disable */
export type HttpMethod = 'GET' | 'PUT' | 'POST' | 'DELETE' | 'PATCH'

export interface OperationMeta {
  operationId: string
  method: HttpMethod
  /** Path template as in the spec, e.g. /users/{userId}. */
  path: string
  /** x-permission: a permission code, AUTHENTICATED or PUBLIC. */
  permission: string
  /** x-idempotent: the client must send an Idempotency-Key. */
  idempotent: boolean
  /** x-approval: MANAGER / OWNER PIN approval inline, or null. */
  approval: 'MANAGER' | 'OWNER' | null
  /** security: [] - no bearer token is sent. */
  noBearer: boolean
  /** x-auth: INLINE_CREDENTIALS - credentials travel in the body. */
  inlineCredentials: boolean
  /** x-terminal: REQUIRED - 403 TERMINAL_REQUIRED in a personal session (ADR-008). */
  terminalRequired: boolean
}

export const OPERATIONS: readonly OperationMeta[] = ${JSON.stringify(ops, null, 2)}

export const API_VERSION = ${JSON.stringify(spec.info?.version ?? 'unknown')}
`

mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, body, 'utf8')
console.log(`gen-api-meta: ${ops.length} operations -> ${output}`)
